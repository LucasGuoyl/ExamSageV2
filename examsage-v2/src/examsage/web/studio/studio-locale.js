function ui(label) {
  return studyLanguage === 'en' && Object.hasOwn(englishCopy, label) ? englishCopy[label] : label;
}

function relationLabel(basis) {
  if (studyLanguage !== 'en') return basis;
  const shared = /^两份原文均出现“(.+)”，可核对是否讨论同一知识点。$/u.exec(basis);
  if (shared) return 'Both sources contain “' + shared[1] + '”. Check whether they discuss the same concept.';
  const context = /^此页是 (.+) 的上下文，小问正文未在本页单独定位。$/u.exec(basis);
  if (context) return 'This page provides context for ' + context[1] + '. The subquestion has not been located separately on this page.';
  return ui(basis);
}

function serviceError(message, code) {
  if (!message || studyLanguage !== 'en') return message;
  const localized = ui(message);
  if (localized !== message || !/\p{Script=Han}/u.test(message)) return localized;
  const runtime = {
    not_installed: 'Install the official Codex desktop app and open it before trying again.',
    startup_failed: 'Codex could not start. Check the desktop app and try again.',
    startup_denied: 'Codex could not start in this environment.',
    chatgpt_login_required: 'Sign in to the Codex desktop app with your ChatGPT account.',
    usage_limit: 'Your current ChatGPT plan has reached its usage limit.',
    usage_unknown: 'Codex could not confirm included usage for your plan.',
    model_unavailable: 'No model is available for this ChatGPT plan.',
    connection_closed: 'The model connection closed. You can retry this question.',
    timeout: 'The model connection timed out. Try the question again.',
    cancelled: 'Response stopped.'
  };
  return runtime[code] || 'The operation could not be completed. Check the selected course, files and Codex connection, then try again.';
}

